#!/usr/bin/env python3
"""Plot leader/follower trajectory and velocity vectors from swarm logs.

Supports merged CSVs generated by log_merger.py:
- merged_<ts>.csv (GPS aligned)
- merged_<ts>_timeline.csv (full timeline)

Also supports OLD follower debug logs:
- follower_log_<ts>.csv (single file with own_* + ldr_* fields)

Outputs:
1) NE trajectory plot (leader + follower) with velocity quivers
2) Velocity-vs-time plots (vn, ve, speed) for both drones

Usage:
  python plot_swarm_trajectory.py --auto
  python plot_swarm_trajectory.py --csv merged_20260305_180102_timeline.csv
  python plot_swarm_trajectory.py --csv merged_20260305_180102.csv --quiver-step 10
    python plot_swarm_trajectory.py --csv follower_log_20260304_134410.csv
"""

import argparse
import glob
import math
import os
from typing import Tuple

import matplotlib.pyplot as plt
from matplotlib.animation import FuncAnimation
import numpy as np
import pandas as pd

METERS_PER_DEG = 111_320.0


def find_latest_merged() -> str:
    candidates = sorted(glob.glob('merged_*.csv'))
    if not candidates:
        candidates = sorted(glob.glob('follower_log_*.csv'))
    if not candidates:
        raise FileNotFoundError('No merged_*.csv or follower_log_*.csv found in current directory')
    timeline = [p for p in candidates if p.endswith('_timeline.csv')]
    return timeline[-1] if timeline else candidates[-1]


def pick_cols(df: pd.DataFrame) -> dict:
    """Pick leader/follower position+velocity columns across supported schemas."""

    # timeline schema from log_merger.py
    if {'ldr_lat', 'ldr_lon', 'fol_lat', 'fol_lon'}.issubset(df.columns):
        cols = {
            't': 'gcs_ts',
            'ldr_lat': 'ldr_lat', 'ldr_lon': 'ldr_lon', 'ldr_alt': 'ldr_rel_alt',
            'ldr_vn': 'ldr_vn', 'ldr_ve': 'ldr_ve',
            'fol_lat': 'fol_lat', 'fol_lon': 'fol_lon', 'fol_alt': 'fol_rel_alt',
            'fol_vn': 'fol_vn', 'fol_ve': 'fol_ve',
        }
        return cols

    # gps-aligned schema from merge_gps_events() (suffix _ldr/_fol)
    if {'lat_ldr', 'lon_ldr', 'lat_fol', 'lon_fol'}.issubset(df.columns):
        cols = {
            't': 'gcs_ts',
            'ldr_lat': 'lat_ldr', 'ldr_lon': 'lon_ldr', 'ldr_alt': 'rel_alt_ldr',
            'ldr_vn': 'vn_ldr', 'ldr_ve': 've_ldr',
            'fol_lat': 'lat_fol', 'fol_lon': 'lon_fol', 'fol_alt': 'rel_alt_fol',
            'fol_vn': 'vn_fol', 'fol_ve': 've_fol',
        }
        return cols

    # older explicit schema fallback
    if {'leader_lat', 'leader_lon', 'follower_lat', 'follower_lon'}.issubset(df.columns):
        cols = {
            't': 'gcs_time',
            'ldr_lat': 'leader_lat', 'ldr_lon': 'leader_lon', 'ldr_alt': 'leader_alt',
            'ldr_vn': 'leader_vn', 'ldr_ve': 'leader_ve',
            'fol_lat': 'follower_lat', 'fol_lon': 'follower_lon', 'fol_alt': 'follower_alt',
            'fol_vn': 'follower_vn', 'fol_ve': 'follower_ve',
        }
        return cols

    # old follower debug log schema (single file): own_* + ldr_*
    if {'own_lat', 'own_lon', 'ldr_lat', 'ldr_lon', 'own_vn', 'own_ve', 'ldr_vn', 'ldr_ve'}.issubset(df.columns):
        cols = {
            't': 'time',
            'ldr_lat': 'ldr_lat', 'ldr_lon': 'ldr_lon', 'ldr_alt': 'ldr_alt',
            'ldr_vn': 'ldr_vn', 'ldr_ve': 'ldr_ve',
            'fol_lat': 'own_lat', 'fol_lon': 'own_lon', 'fol_alt': 'own_alt',
            'fol_vn': 'own_vn', 'fol_ve': 'own_ve',
        }
        return cols

    raise ValueError(
        'Unsupported CSV schema. Expected timeline columns (ldr_*/fol_*), '
        'or merged columns (*_ldr/*_fol).'
    )


def to_numeric(df: pd.DataFrame, cols: list) -> pd.DataFrame:
    for col in cols:
        if col in df.columns:
            df[col] = pd.to_numeric(df[col], errors='coerce')
    return df


def series_filled(df: pd.DataFrame, col: str, length: int) -> np.ndarray:
    """Numeric series with ffill/bfill; falls back to zeros only if column absent."""
    if col not in df.columns:
        return np.zeros(length, dtype=float)
    s = pd.to_numeric(df[col], errors='coerce').ffill().bfill()
    return s.to_numpy(dtype=float)


def parse_time_to_seconds(series: pd.Series) -> np.ndarray:
    """Parse time column into seconds from start.

    Supports:
    - Numeric unix/relative seconds
    - HH:MM:SS.xx strings used in old follower_debug_log
    """
    num = pd.to_numeric(series, errors='coerce')
    if num.notna().mean() > 0.95:
        t = num.to_numpy(dtype=float)
        return t - t[0]

    dt = pd.to_datetime(series, format='%H:%M:%S.%f', errors='coerce')
    if dt.notna().mean() > 0.8:
        sec = (dt.dt.hour * 3600.0 +
               dt.dt.minute * 60.0 +
               dt.dt.second +
               dt.dt.microsecond / 1e6).to_numpy(dtype=float)
        return sec - sec[0]

    raise ValueError('Unable to parse time axis from column')


def latlon_to_ne(lat: np.ndarray, lon: np.ndarray, ref_lat: float, ref_lon: float) -> Tuple[np.ndarray, np.ndarray]:
    dn = (lat - ref_lat) * METERS_PER_DEG
    de = (lon - ref_lon) * METERS_PER_DEG * np.cos(np.radians(ref_lat))
    return dn, de


def valid_gps_mask(df: pd.DataFrame, cols: dict) -> pd.Series:
    """True where both leader and follower GPS are valid (not 0,0 and finite)."""
    ldr_ok = (
        np.isfinite(df[cols['ldr_lat']]) & np.isfinite(df[cols['ldr_lon']]) &
        ((df[cols['ldr_lat']] != 0.0) | (df[cols['ldr_lon']] != 0.0))
    )
    fol_ok = (
        np.isfinite(df[cols['fol_lat']]) & np.isfinite(df[cols['fol_lon']]) &
        ((df[cols['fol_lat']] != 0.0) | (df[cols['fol_lon']] != 0.0))
    )
    return ldr_ok & fol_ok


def remove_stale_snapbacks(df: pd.DataFrame, cols: dict) -> pd.DataFrame:
    """Remove rows where GPS snaps to a stale/aliased position.

    Two filters applied per drone:

    1. **Cross-drone aliasing** — Some loggers snapshot the peer's position
       into the own-GPS columns on PEER callback rows.  These show up as
       rows where follower lat/lon ≈ leader lat/lon.  If the two drones
       are flying different trajectories these rows are bogus.  We detect
       them by checking when the follower position is suspiciously close
       to the leader position AND the next row jumps back, indicating the
       row is a foreign reading, not real own-GPS motion.

    2. **Zigzag snap-back** — Rows where GPS jumps far from both
       neighbours while the neighbours are continuous.

    Both are removed to produce a clean monotonic trajectory.
    """
    n = len(df)
    if n < 5:
        return df

    # ── Pass 1: cross-drone alias filter ──────────────────────
    # Remove rows where fol position ≈ ldr position AND it looks like
    # an outlier (big jump from prev AND next row).
    lat_l = df[cols['ldr_lat']].to_numpy(dtype=float)
    lon_l = df[cols['ldr_lon']].to_numpy(dtype=float)
    lat_f = df[cols['fol_lat']].to_numpy(dtype=float)
    lon_f = df[cols['fol_lon']].to_numpy(dtype=float)

    cos_lat = np.cos(np.radians(np.nanmean(lat_f)))
    sep_n = (lat_f - lat_l) * METERS_PER_DEG
    sep_e = (lon_f - lon_l) * METERS_PER_DEG * cos_lat
    sep_m = np.sqrt(sep_n**2 + sep_e**2)

    # For each row, check if fol jumped far from prev AND next fol position
    fol_dn = np.diff(lat_f) * METERS_PER_DEG
    fol_de = np.diff(lon_f) * METERS_PER_DEG * cos_lat
    fol_step = np.sqrt(fol_dn**2 + fol_de**2)

    ALIAS_SEP = 1.0  # fol ≈ ldr within this many metres
    ALIAS_JUMP = 2.0  # minimum jump to/from the aliased row

    keep = np.ones(n, dtype=bool)
    for i in range(1, n - 1):
        if sep_m[i] < ALIAS_SEP:
            # fol is suspiciously at leader's position
            if fol_step[i - 1] > ALIAS_JUMP and fol_step[i] > ALIAS_JUMP:
                keep[i] = False

    # Also catch first and last row aliases
    if n > 1 and sep_m[0] < ALIAS_SEP and fol_step[0] > ALIAS_JUMP:
        keep[0] = False
    if n > 1 and sep_m[-1] < ALIAS_SEP and fol_step[-1] > ALIAS_JUMP:
        keep[-1] = False

    df = df.iloc[keep].copy()
    n = len(df)

    # ── Pass 2: generic zigzag snap-back filter ───────────────
    for role in ('ldr', 'fol'):
        lat = df[cols[f'{role}_lat']].to_numpy(dtype=float)
        lon = df[cols[f'{role}_lon']].to_numpy(dtype=float)
        dn = np.diff(lat) * METERS_PER_DEG
        de = np.diff(lon) * METERS_PER_DEG * np.cos(np.radians(np.nanmean(lat)))
        dist = np.sqrt(dn**2 + de**2)

        keep = np.ones(n, dtype=bool)
        THRESH = 2.0
        for i in range(1, n - 1):
            if dist[i - 1] > THRESH and dist[i] > THRESH:
                gap_n = (lat[i + 1] - lat[i - 1]) * METERS_PER_DEG
                gap_e = (lon[i + 1] - lon[i - 1]) * METERS_PER_DEG * np.cos(np.radians(lat[i]))
                gap = math.sqrt(gap_n**2 + gap_e**2)
                if gap < max(dist[i - 1], dist[i]) * 0.8:
                    keep[i] = False

        df = df.iloc[keep].copy()
        n = len(df)

    return df


def animate_trajectory(
    trel: np.ndarray,
    ldr_e: np.ndarray,
    ldr_n: np.ndarray,
    fol_e: np.ndarray,
    fol_n: np.ndarray,
    ldr_ve: np.ndarray,
    ldr_vn: np.ndarray,
    fol_ve: np.ndarray,
    fol_vn: np.ndarray,
    interval_ms: int,
):
    """Animate trajectory over time with only current velocity vectors shown."""
    fig, ax = plt.subplots(figsize=(10, 8))

    # Fixed axis limits so frame doesn't jump.
    all_e = np.concatenate([ldr_e, fol_e])
    all_n = np.concatenate([ldr_n, fol_n])
    e_pad = max(1.0, 0.08 * (all_e.max() - all_e.min() + 1e-6))
    n_pad = max(1.0, 0.08 * (all_n.max() - all_n.min() + 1e-6))
    ax.set_xlim(all_e.min() - e_pad, all_e.max() + e_pad)
    ax.set_ylim(all_n.min() - n_pad, all_n.max() + n_pad)

    ax.set_xlabel('East (m)')
    ax.set_ylabel('North (m)')
    ax.set_title('Leader/Follower Trajectory (Time Animation)')
    ax.grid(True, alpha=0.3)
    ax.axis('equal')

    ldr_line, = ax.plot([], [], 'r-', lw=2, label='Leader trajectory')
    fol_line, = ax.plot([], [], 'b-', lw=2, label='Follower trajectory')

    ldr_dot, = ax.plot([], [], 'ro', ms=6, label='Leader current')
    fol_dot, = ax.plot([], [], 'bo', ms=6, label='Follower current')

    # Start markers
    ax.scatter([ldr_e[0]], [ldr_n[0]], c='darkred', marker='o', s=70, label='Leader start')
    ax.scatter([fol_e[0]], [fol_n[0]], c='navy', marker='o', s=70, label='Follower start(home)')

    ldr_q = ax.quiver([], [], [], [], color='tomato', angles='xy', scale_units='xy', scale=1, width=0.005)
    fol_q = ax.quiver([], [], [], [], color='dodgerblue', angles='xy', scale_units='xy', scale=1, width=0.005)

    time_text = ax.text(0.02, 0.98, '', transform=ax.transAxes, va='top')
    ax.legend(loc='best')

    def init():
        ldr_line.set_data([], [])
        fol_line.set_data([], [])
        ldr_dot.set_data([], [])
        fol_dot.set_data([], [])
        time_text.set_text('t = 0.0 s')
        return ldr_line, fol_line, ldr_dot, fol_dot, time_text

    def update(i):
        nonlocal ldr_q, fol_q
        ldr_line.set_data(ldr_e[:i + 1], ldr_n[:i + 1])
        fol_line.set_data(fol_e[:i + 1], fol_n[:i + 1])
        ldr_dot.set_data([ldr_e[i]], [ldr_n[i]])
        fol_dot.set_data([fol_e[i]], [fol_n[i]])

        ldr_q.remove()
        fol_q.remove()
        ldr_q = ax.quiver(ldr_e[i], ldr_n[i], ldr_ve[i], ldr_vn[i],
                          color='tomato', angles='xy', scale_units='xy', scale=1, width=0.005)
        fol_q = ax.quiver(fol_e[i], fol_n[i], fol_ve[i], fol_vn[i],
                          color='dodgerblue', angles='xy', scale_units='xy', scale=1, width=0.005)

        time_text.set_text(f't = {trel[i]:.2f} s')
        return ldr_line, fol_line, ldr_dot, fol_dot, ldr_q, fol_q, time_text

    ani = FuncAnimation(
        fig,
        update,
        frames=len(trel),
        init_func=init,
        interval=max(10, int(interval_ms)),
        blit=False,
        repeat=False,
    )
    return fig, ani


def main():
    parser = argparse.ArgumentParser(description='Plot swarm trajectory + velocity vectors')
    parser.add_argument('--csv', type=str, default=None,
                        help='Path to merged CSV (merged_*.csv or *_timeline.csv)')
    parser.add_argument('--auto', action='store_true',
                        help='Auto-pick latest merged CSV in current directory')
    parser.add_argument('--quiver-step', type=int, default=8,
                        help='Use every Nth point for velocity arrows (default: 8)')
    parser.add_argument('--no-quiver', action='store_true',
                        help='Disable velocity arrows in static trajectory plot')
    parser.add_argument('--quiver-scale', type=float, default=3.0,
                        help='Arrow scale for static quiver (default: 3.0, larger=shorter arrows)')
    parser.add_argument('--save-prefix', type=str, default='swarm_plot',
                        help='Output image prefix (default: swarm_plot)')
    parser.add_argument('--leader-id', type=int, default=None,
                        help='Optional: filter old follower log to one leader ID (e.g., 1)')
    parser.add_argument('--animate', action='store_true',
                        help='Show time-flow animation (single evolving velocity vectors)')
    parser.add_argument('--interval-ms', type=int, default=120,
                        help='Animation frame interval in milliseconds (default: 120)')
    parser.add_argument('--no-show', action='store_true',
                        help='Do not open interactive plot windows (save files only)')
    args = parser.parse_args()

    if args.auto or not args.csv:
        csv_path = find_latest_merged()
    else:
        csv_path = args.csv

    if not os.path.exists(csv_path):
        raise FileNotFoundError(csv_path)

    df = pd.read_csv(csv_path, low_memory=False)

    if args.leader_id is not None and 'ldr_id' in df.columns:
        df = df[df['ldr_id'] == args.leader_id].copy()

    cols = pick_cols(df)

    needed = [
        cols['ldr_lat'], cols['ldr_lon'], cols['ldr_vn'], cols['ldr_ve'],
        cols['fol_lat'], cols['fol_lon'], cols['fol_vn'], cols['fol_ve'],
    ]
    needed = [c for c in needed if c in df.columns]
    df = to_numeric(df, needed)
    df = df.dropna(subset=[cols['ldr_lat'], cols['ldr_lon'], cols['fol_lat'], cols['fol_lon']]).copy()

    # Remove initial/unfixed GPS rows (0,0) for either drone.
    # Keep only rows where BOTH leader and follower have valid GPS.
    gps_ok = valid_gps_mask(df, cols)
    if gps_ok.any():
        first_valid_idx = gps_ok[gps_ok].index[0]
        df = df.loc[first_valid_idx:].copy()
        # Recompute mask on trimmed frame and keep only valid GPS rows.
        gps_ok = valid_gps_mask(df, cols)
        df = df[gps_ok].copy()

    # Remove stale GPS snap-back rows (zigzag between home and real position).
    before = len(df)
    df = remove_stale_snapbacks(df, cols)
    removed = before - len(df)
    if removed:
        print(f"Filtered {removed} stale GPS snap-back rows ({removed}/{before})")

    if len(df) < 3:
        raise RuntimeError('Not enough valid rows to plot (need >= 3)')

    # time axis (seconds from start)
    trel = parse_time_to_seconds(df[cols['t']])

    # reference: follower initial point (home)
    ref_lat = float(df[cols['fol_lat']].iloc[0])
    ref_lon = float(df[cols['fol_lon']].iloc[0])

    ldr_n, ldr_e = latlon_to_ne(df[cols['ldr_lat']].to_numpy(), df[cols['ldr_lon']].to_numpy(), ref_lat, ref_lon)
    fol_n, fol_e = latlon_to_ne(df[cols['fol_lat']].to_numpy(), df[cols['fol_lon']].to_numpy(), ref_lat, ref_lon)

    ldr_vn = series_filled(df, cols['ldr_vn'], len(ldr_n))
    ldr_ve = series_filled(df, cols['ldr_ve'], len(ldr_n))
    fol_vn = series_filled(df, cols['fol_vn'], len(fol_n))
    fol_ve = series_filled(df, cols['fol_ve'], len(fol_n))

    if args.animate:
        fig_anim, _ = animate_trajectory(
            trel, ldr_e, ldr_n, fol_e, fol_n,
            ldr_ve, ldr_vn, fol_ve, fol_vn,
            interval_ms=args.interval_ms,
        )
        out_anim = f"{args.save_prefix}_animation_firstframe.png"
        fig_anim.tight_layout()
        fig_anim.savefig(out_anim, dpi=160)
        print(f"Loaded: {csv_path}")
        print(f"Rows used: {len(df)}")
        print(f"Saved: {out_anim}")
        print("Animation mode ON: one evolving trajectory + current velocity vectors.")
        print("Reference origin = follower start position (home).")
        print("Axes: X=East, Y=North.")
        if not args.no_show:
            plt.show()
        return

    # ──────────────────────────────────────────────────────────
    # Figure 1: Trajectory with velocity vectors (N vs E)
    # ──────────────────────────────────────────────────────────
    fig1, ax = plt.subplots(figsize=(10, 8))

    ax.plot(ldr_e, ldr_n, 'r-', lw=2, label='Leader trajectory')
    ax.plot(fol_e, fol_n, 'b-', lw=2, label='Follower trajectory')

    ax.scatter([ldr_e[0]], [ldr_n[0]], c='darkred', marker='o', s=80, label='Leader start')
    ax.scatter([fol_e[0]], [fol_n[0]], c='navy', marker='o', s=80, label='Follower start(home)')
    ax.scatter([ldr_e[-1]], [ldr_n[-1]], c='red', marker='x', s=80, label='Leader end')
    ax.scatter([fol_e[-1]], [fol_n[-1]], c='blue', marker='x', s=80, label='Follower end')

    step = max(1, int(args.quiver_step))
    idx = np.arange(0, len(df), step)

    if not args.no_quiver:
        # quiver scale_units='xy', scale=1 means arrows in meters/sec on same axes
        ax.quiver(ldr_e[idx], ldr_n[idx], ldr_ve[idx], ldr_vn[idx],
                  color='tomato', alpha=0.6, angles='xy', scale_units='xy', scale=args.quiver_scale,
                  width=0.003)
        ax.quiver(fol_e[idx], fol_n[idx], fol_ve[idx], fol_vn[idx],
                  color='dodgerblue', alpha=0.6, angles='xy', scale_units='xy', scale=args.quiver_scale,
                  width=0.003)

    ax.set_xlabel('East (m)')
    ax.set_ylabel('North (m)')
    ax.set_title('Leader/Follower Trajectory with Velocity Vectors')
    ax.grid(True, alpha=0.3)
    ax.axis('equal')
    ax.legend(loc='best')

    out1 = f"{args.save_prefix}_trajectory.png"
    fig1.tight_layout()
    fig1.savefig(out1, dpi=160)

    # ──────────────────────────────────────────────────────────
    # Figure 2: Velocity vs time
    # ──────────────────────────────────────────────────────────
    ldr_speed = np.sqrt(ldr_vn**2 + ldr_ve**2)
    fol_speed = np.sqrt(fol_vn**2 + fol_ve**2)

    fig2, axs = plt.subplots(3, 1, figsize=(12, 9), sharex=True)

    axs[0].plot(trel, ldr_vn, 'r-', lw=1.5, label='Leader vn')
    axs[0].plot(trel, fol_vn, 'b-', lw=1.5, label='Follower vn')
    axs[0].set_ylabel('vn (m/s)')
    axs[0].grid(True, alpha=0.3)
    axs[0].legend(loc='best')

    axs[1].plot(trel, ldr_ve, 'r-', lw=1.5, label='Leader ve')
    axs[1].plot(trel, fol_ve, 'b-', lw=1.5, label='Follower ve')
    axs[1].set_ylabel('ve (m/s)')
    axs[1].grid(True, alpha=0.3)
    axs[1].legend(loc='best')

    axs[2].plot(trel, ldr_speed, 'r-', lw=2, label='Leader speed')
    axs[2].plot(trel, fol_speed, 'b-', lw=2, label='Follower speed')
    axs[2].set_ylabel('speed (m/s)')
    axs[2].set_xlabel('Time since start (s)')
    axs[2].grid(True, alpha=0.3)
    axs[2].legend(loc='best')

    out2 = f"{args.save_prefix}_velocity_time.png"
    fig2.tight_layout()
    fig2.savefig(out2, dpi=160)

    print(f"Loaded: {csv_path}")
    print(f"Rows used: {len(df)}")
    print(f"Saved: {out1}")
    print(f"Saved: {out2}")
    print("Reference origin = follower start position (home).")
    print("Axes: X=East, Y=North.")

    if not args.no_show:
        plt.show()


if __name__ == '__main__':
    main()
